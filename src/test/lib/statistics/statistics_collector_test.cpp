TEST_F(StatisticsCollectorTest, GetMinMaxValues) {
  EXPECT_EQ(collector_->GetNumColumns(), 16);

  // Check each type in the TPC-H lineitem table.

  // int
  auto order_key_min_max = collector_->GetMinMaxForColumn(0);
  auto order_key_min = std::get<int64_t>(order_key_min_max.first);
  auto order_key_max = std::get<int64_t>(order_key_min_max.second);
  EXPECT_LE(order_key_min, order_key_max);

  // double
  auto quantity_key_min_max = collector_->GetMinMaxForColumn(4);
  auto quantity_key_min = std::get<double>(quantity_key_min_max.first);
  auto quantity_key_max = std::get<double>(quantity_key_min_max.second);
  EXPECT_LE(quantity_key_min, quantity_key_max);

  // varchar
  auto comment_key_min_max = collector_->GetMinMaxForColumn(15);
  auto comment_key_min = std::get<std::string>(comment_key_min_max.first);
  EXPECT_FALSE(comment_key_min.empty());
  auto comment_key_max = std::get<std::string>(comment_key_min_max.second);
  EXPECT_FALSE(comment_key_max.empty());
  EXPECT_LE(comment_key_min, comment_key_max);

  // char
  auto shipinstruct_key_min_max = collector_->GetMinMaxForColumn(13);
  auto shipinstruct_key_min = std::get<std::string>(shipinstruct_key_min_max.first);
  EXPECT_FALSE(shipinstruct_key_min.empty());
  auto shipinstruct_key_max = std::get<std::string>(shipinstruct_key_min_max.second);
  EXPECT_FALSE(shipinstruct_key_max.empty());
  EXPECT_LE(shipinstruct_key_min, shipinstruct_key_max);

  // date
  auto shipdate_key_min_max = collector_->GetMinMaxForColumn(10);
  auto shipdate_key_min = std::get<std::string>(shipdate_key_min_max.first);
  auto shipdate_key_max = std::get<std::string>(shipdate_key_min_max.second);
  EXPECT_LE(shipdate_key_min, shipdate_key_max);

  const std::regex date_regex("[12][0-9]{3}-[01][0-9]-[0123][0-9]");
  EXPECT_TRUE(std::regex_match(shipdate_key_min, date_regex));
  EXPECT_TRUE(std::regex_match(shipdate_key_max, date_regex));
}

TEST_F(StatisticsCollectorTest, GetSchema) {
  const std::shared_ptr<TableColumnDefinitions> schema = collector_->GetSchema();

  std::vector<std::string> expected_names = {
      "orderkey",   "partkey",    "suppkey",  "linenumber", "quantity",    "extendedprice", "discount", "tax",
      "returnflag", "linestatus", "shipdate", "commitdate", "receiptdate", "shipinstruct",  "shipmode", "comment"};
  std::vector<DataType> expected_types = {DataType::kLong,   DataType::kLong,   DataType::kLong,   DataType::kLong,
                                          DataType::kDouble, DataType::kDouble, DataType::kDouble, DataType::kDouble,
                                          DataType::kString, DataType::kString, DataType::kLong,   DataType::kLong,
                                          DataType::kLong,   DataType::kString, DataType::kString, DataType::kString};

  EXPECT_EQ(schema->size(), 16);
  EXPECT_EQ(schema->size(), expected_names.size());
  EXPECT_EQ(schema->size(), expected_types.size());

  for (size_t column_id = 0; column_id < schema->size(); ++column_id) {
    EXPECT_EQ((*schema)[column_id].name, expected_names[column_id]);
    EXPECT_EQ((*schema)[column_id].data_type, expected_types[column_id]);
  }
}

